#!/usr/bin/env bash
# POL16 house style: no U+2013 / U+2014 in tracked text; workflows with issue, PR or comment outputs import
# shared/reporting.md (fixed report format). Repo mode scans every tracked text file except bad/POL16.md.
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"
DASH=$'\xe2\x80\x93|\xe2\x80\x94'
REPORTING=' create-issue create-discussion add-comment create-pull-request create-pull-request-review-comment submit-pull-request-review update-issue '
dash_scan() { local n; while IFS=: read -r n _; do hit "$(rel "$1")" "$n" POL16 "en or em dash (use a hyphen or rephrase)"; done < <(grep -nE -- "$DASH" "$1" 2>/dev/null); }

if repo_mode "$@"; then
  while IFS= read -r f; do
    case "$f" in test/fixtures/bad/POL16.md|*.lock.yml) continue ;; esac  # locks are generated by gh-aw
    [ -f "$POL_ROOT/$f" ] && grep -Iq . "$POL_ROOT/$f" 2>/dev/null && dash_scan "$POL_ROOT/$f"
  done < <(git -C "$POL_ROOT" ls-files)
else
  for f in $(targets "$@"); do dash_scan "$f"; done
fi
for f in $(targets "$@"); do
  is_workflow "$f" || continue
  needs=0; for o in $(so_outputs "$f"); do [[ "$REPORTING" == *" $o "* ]] && needs=1; done
  if [ $needs = 1 ] && [ "$(q "$f" '[.imports[]? | (select(tag == "!!str"), .uses?, .path?)] | map(select(. != null and test("shared/reporting\.md"))) | length')" = 0 ]; then
    hit "$(rel "$f")" "$(qline "$f" '.["safe-outputs"]')" POL16 "writes issues/PRs/comments but does not import shared/reporting.md"
  fi
done
pol_done
